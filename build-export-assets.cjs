const {createCanvas, loadImage} = require(require.resolve('@napi-rs/canvas', {paths:[process.env.SPORTSFEST_NODE_MODULES || 'C:/Users/tamon/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules']}));
async function png(file, width, height) {
  const image = await loadImage(file), canvas = createCanvas(width,height), ctx=canvas.getContext('2d');
  const scale=Math.min(width/image.width,height/image.height);
  ctx.drawImage(image,(width-image.width*scale)/2,(height-image.height*scale)/2,image.width*scale,image.height*scale);
  return canvas.toDataURL('image/png');
}
